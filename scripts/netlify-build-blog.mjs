function sitemapEntry(loc, lastmod) {
  return `  <url>\n    <loc>${escapeHtml(loc)}</loc>\n    <lastmod>${escapeHtml(lastmod)}</lastmod>\n  </url>`;
}

function updateSitemap(currentSitemap, posts, archivePageCount) {
  const openTag = currentSitemap.match(/<urlset\b[^>]*>/)?.[0]
    || '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">';
  const existingEntries = [...currentSitemap.matchAll(/<url>[\s\S]*?<\/url>/g)]
    .map((match) => match[0])
    .filter((entry) => !entry.includes(`${siteUrl}/blog/`) && !entry.includes(`${siteUrl}/blog-page-`));

  const postEntries = posts.map((post) => sitemapEntry(
    `${siteUrl}/blog/${normalizeSlug(post)}.html`,
    post.date || new Date().toISOString().slice(0, 10)
  ));
  const archiveEntries = Array.from({ length: Math.max(archivePageCount - 1, 0) }, (_, index) => {
    const page = index + 2;
    const lastmod = posts[index * archivePageSize + archivePageSize]?.date || posts[0]?.date || "";
    return sitemapEntry(`${siteUrl}/blog-page-${page}.html`, lastmod);
  });

  const allEntries = [...existingEntries, ...postEntries, ...archiveEntries];
  const declaration = currentSitemap.startsWith("<?xml")
    ? currentSitemap.slice(0, currentSitemap.indexOf("?>") + 2)
    : '<?xml version="1.0" encoding="UTF-8"?>';

  return `${declaration}\n${openTag}\n${allEntries.join("\n")}\n</urlset>\n`;
}

async function writeArticlePages(posts) {
  await fs.mkdir(articlesDir, { recursive: true });
  const validSlugs = new Set();

  for (const post of posts) {
    const slug = normalizeSlug(post);
    if (validSlugs.has(slug)) {
      throw new Error(`Duplicate blog slug: ${slug}`);
    }
    validSlugs.add(slug);
    await fs.writeFile(path.join(articlesDir, `${slug}.html`), renderArticle(post, slug), "utf8");
  }

  const existingFiles = await fs.readdir(articlesDir, { withFileTypes: true });
  for (const entry of existingFiles) {
    if (!entry.isFile() || !entry.name.endsWith(".html") || validSlugs.has(entry.name.slice(0, -5))) {
      continue;
    }

    const filePath = path.join(articlesDir, entry.name);
    const contents = await fs.readFile(filePath, "utf8");
    if (contents.includes(generatedMarker)) {
      await fs.unlink(filePath);
    }
  }
}

async function writeArchivePages(template, posts) {
  const pageCount = Math.ceil(posts.length / archivePageSize);
  const files = await fs.readdir(rootDir, { withFileTypes: true });

  for (const entry of files) {
    const match = entry.name.match(/^blog-page-(\d+)\.html$/);
    if (!entry.isFile() || !match || Number(match[1]) <= pageCount) {
      continue;
    }

    const filePath = path.join(rootDir, entry.name);
    const contents = await fs.readFile(filePath, "utf8");
    if (contents.includes(generatedArchiveMarker)) {
      await fs.unlink(filePath);
    }
  }

  await fs.writeFile(blogPagePath, renderArchivePage(template, 1, posts, pageCount), "utf8");
  for (let page = 2; page <= pageCount; page += 1) {
    const pagePath = path.join(rootDir, `blog-page-${page}.html`);
    await fs.writeFile(pagePath, renderArchivePage(template, page, posts, pageCount), "utf8");
  }

  return pageCount;
}

async function main() {
  const posts = JSON.parse(await fs.readFile(postsPath, "utf8"))
    .filter((post) => post && post.title && (post.slug || post.title))
    .sort((a, b) => new Date(b.date || 0) - new Date(a.date || 0));

  await writeArticlePages(posts);

  const blogTemplate = await fs.readFile(blogPagePath, "utf8");
  const archivePageCount = await writeArchivePages(blogTemplate, posts);

  const currentSitemap = await fs.readFile(sitemapPath, "utf8");
  await fs.writeFile(sitemapPath, updateSitemap(currentSitemap, posts, archivePageCount), "utf8");

  console.log(`Generated ${posts.length} individual blog pages across ${archivePageCount} archive pages and updated the sitemap.`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
