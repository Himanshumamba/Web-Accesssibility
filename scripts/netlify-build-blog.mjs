import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const rootDir = process.cwd();
const siteUrl = "https://websiteaccessibilityfix.com";
const postsPath = path.join(rootDir, "blog-posts.json");
const blogPagePath = path.join(rootDir, "blog.html");
const sitemapPath = path.join(rootDir, "sitemap.xml");
const articlesDir = path.join(rootDir, "blog");
const generatedMarker = "Generated by scripts/netlify-build-blog.mjs";
const generatedArchiveMarker = `${generatedMarker} (paginated archive)`;
const archivePageSize = 9;
const paginationMarker = /<!-- BLOG_PAGINATION_START -->[\s\S]*?<!-- BLOG_PAGINATION_END -->/;

function escapeHtml(value = "") {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function formatPlainText(value = "") {
  return escapeHtml(value).replace(/`([^`]+)`/g, "<code>$1</code>");
}

function formatText(value = "") {
  const anchorPattern = /<a\s+href=(['"])([^'"]+)\1>(.*?)<\/a>/gi;
  let output = "";
  let lastIndex = 0;
  let match;

  while ((match = anchorPattern.exec(String(value))) !== null) {
    output += formatPlainText(value.slice(lastIndex, match.index));
    let href = match[2].trim();
    if (href.startsWith("blog.html#")) {
      href = `../blog/${href.slice("blog.html#".length)}.html`;
    } else if (/^https?:\/\//i.test(href)) {
      // Keep vetted external destinations unchanged.
    } else {
      href = `../${href.replace(/^\.\//, "")}`;
    }
    output += `<a href="${escapeHtml(href)}">${formatPlainText(match[3])}</a>`;
    lastIndex = match.index + match[0].length;
  }

  return output + formatPlainText(String(value).slice(lastIndex));
}

function normalizeSlug(post) {
  const slug = String(post.slug || post.title || "")
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");

  if (!slug) {
    throw new Error(`Blog post is missing a usable slug: ${post.title || "(untitled)"}`);
  }

  return slug;
}

function formatArchiveDate(value = "") {
  const dateValue = String(value).slice(0, 10);
  const date = new Date(`${dateValue}T00:00:00Z`);
  if (!dateValue || Number.isNaN(date.getTime())) {
    return escapeHtml(value);
  }

  return new Intl.DateTimeFormat("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC"
  }).format(date);
}

function renderBodyBlock(block) {
  if (typeof block === "string") {
    return `<p>${formatText(block)}</p>`;
  }
  if (!block || typeof block !== "object") {
    return "";
  }
  if (block.type === "h2") {
    const idAttr = block.id ? ` id="${escapeHtml(block.id)}"` : "";
    return `<h2${idAttr}>${formatText(block.text || "")}</h2>`;
  }
  if (block.type === "h3") {
    return `<h3>${formatText(block.text || "")}</h3>`;
  }
  if (block.type === "code") {
    return `<pre><code>${escapeHtml(block.text || "")}</code></pre>`;
  }
  if (block.type === "ul" && Array.isArray(block.items)) {
    return `<ul>${block.items.map((item) => `<li>${formatText(item)}</li>`).join("")}</ul>`;
  }
  if (block.type === "ol" && Array.isArray(block.items)) {
    return `<ol>${block.items.map((item) => `<li>${formatText(item)}</li>`).join("")}</ol>`;
  }
  return block.text ? `<p>${formatText(block.text)}</p>` : "";
}

function renderTags(tags = []) {
  if (!Array.isArray(tags) || tags.length === 0) {
    return "";
  }

  return `<ul class="tag-list article-tags" aria-label="Article topics">${tags
    .map((tag) => `<li>${escapeHtml(tag)}</li>`)
    .join("")}</ul>`;
}

function renderArchive(posts) {
  return `<div class="blog-posts">${posts.map((post) => {
    const slug = normalizeSlug(post);
    const href = `blog/${slug}.html`;
    const tags = Array.isArray(post.tags) && post.tags.length
      ? `<p class="blog-kicker">${post.tags.slice(0, 2).map(escapeHtml).join(" · ")}</p>`
      : "";

    return `
    <article class="blog-card card">
      <div class="blog-meta">
        <time datetime="${escapeHtml(post.date || "")}">${formatArchiveDate(post.date || "")}</time>
        <span>${escapeHtml(post.readTime || "4 min read")}</span>
      </div>
      ${tags}
      <h3><a class="blog-link" href="${href}">${escapeHtml(post.title)}</a></h3>
      <p class="blog-excerpt">${escapeHtml(post.excerpt || "")}</p>
      <a class="blog-read-link" href="${href}" aria-label="Read article: ${escapeHtml(post.title)}">Read article <span aria-hidden="true">&rarr;</span></a>
    </article>`;
  }).join("")}</div>`;
}

function archivePageHref(page) {
  return page === 1 ? "blog.html" : `blog-page-${page}.html`;
}

function renderPagination(page, pageCount, totalPosts) {
  if (pageCount <= 1) {
    return "";
  }

  const firstPost = (page - 1) * archivePageSize + 1;
  const lastPost = Math.min(page * archivePageSize, totalPosts);
  const visiblePages = [...new Set([1, page - 1, page, page + 1, pageCount])]
    .filter((number) => number >= 1 && number <= pageCount)
    .sort((a, b) => a - b);
  const pageLinks = [];
  let previousPage = 0;

  for (const pageNumber of visiblePages) {
    if (pageNumber - previousPage > 1) {
      pageLinks.push('<span class="pagination-ellipsis" aria-hidden="true">&hellip;</span>');
    }

    if (pageNumber === page) {
      pageLinks.push(`<span class="pagination-link is-active" aria-current="page" aria-label="Page ${pageNumber}">${pageNumber}</span>`);
    } else {
      pageLinks.push(`<a class="pagination-link" href="${archivePageHref(pageNumber)}" aria-label="Page ${pageNumber}">${pageNumber}</a>`);
    }
    previousPage = pageNumber;
  }

  const previousLink = page > 1
    ? `<a class="pagination-link" href="${archivePageHref(page - 1)}">Previous</a>`
    : '<span class="pagination-link" aria-disabled="true">Previous</span>';
  const nextLink = page < pageCount
    ? `<a class="pagination-link" href="${archivePageHref(page + 1)}">Next</a>`
    : '<span class="pagination-link" aria-disabled="true">Next</span>';

  return `<p class="blog-pagination-summary">Showing ${firstPost}&ndash;${lastPost} of ${totalPosts} articles</p>
    <nav class="blog-pagination" aria-label="Blog pages">
      ${previousLink}
      <div class="pagination-pages">${pageLinks.join("")}</div>
      ${nextLink}
    </nav>`;
}

function renderArchivePage(template, page, posts, pageCount) {
  const start = (page - 1) * archivePageSize;
  const pagePosts = posts.slice(start, start + archivePageSize);
  const archiveMarkers = /<!-- BLOG_ARCHIVE_START -->[\s\S]*?<!-- BLOG_ARCHIVE_END -->/;

  if (!archiveMarkers.test(template)) {
    throw new Error("Could not find BLOG_ARCHIVE markers in blog.html.");
  }
  if (!paginationMarker.test(template)) {
    throw new Error("Could not find BLOG_PAGINATION markers in blog.html.");
  }

  let html = template
    .replace(archiveMarkers, `<!-- BLOG_ARCHIVE_START -->\n  ${renderArchive(pagePosts)}\n  <!-- BLOG_ARCHIVE_END -->`)
    .replace(paginationMarker, `<!-- BLOG_PAGINATION_START -->\n  ${renderPagination(page, pageCount, posts.length)}\n  <!-- BLOG_PAGINATION_END -->`);

  if (page > 1) {
    const pageTitle = `Accessibility Blog | WCAG Tips, ADA Insights & Practical Fixes — Page ${page}`;
    const pageUrl = `${siteUrl}/blog-page-${page}.html`;
    html = html
      .replace("<head>", `<head>\n  <!-- ${generatedArchiveMarker} -->`)
      .replace(/<title>[\s\S]*?<\/title>/, `<title>${escapeHtml(pageTitle)}</title>`)
      .replace(/<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${escapeHtml(pageTitle)}">`)
      .replace(/<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${pageUrl}">`)
      .replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${pageUrl}">`)
      .replace(/<section class="section blog-hero" id="blog-intro">[\s\S]*?<\/section>\s*/, "")
      .replace(/<section class="section" id="blog-topic-hubs">[\s\S]*?<\/section>\s*/, "")
      .replace("<h2>Accessibility Guides</h2>", `<h1>Accessibility Guides &mdash; Page ${page}</h1>`);
  }

  return html;
}

